// Compatibility is restricted to SQL actually used by the decision engine.
// Platform queries use native PostgreSQL through pg directly.
export function translateSql(input, method = "query") {
  let sql = input.trim();
  const pragma = sql.match(/^PRAGMA table_info\(([a-z_]+)\)$/i);
  if (pragma)
    return {
      sql: `SELECT column_name AS name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = $1 ORDER BY ordinal_position`,
      params: [pragma[1]],
    };
  if (/sqlite_master/i.test(sql)) {
    sql = sql.replace(
      /sqlite_master/g,
      `(SELECT table_name AS name, 'table' AS type FROM information_schema.tables WHERE table_schema = current_schema() AND table_type = 'BASE TABLE') AS sqlite_master`,
    );
  }
  sql = sql.replace(
    /INTEGER PRIMARY KEY AUTOINCREMENT/gi,
    "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
  );
  sql = sql.replace(
    /ORDER BY username COLLATE NOCASE/gi,
    "ORDER BY LOWER(username)",
  );
  // SQLite permits ungrouped label columns; PostgreSQL requires a functional
  // dependency or an aggregate. Preserve the same voter groups and counts.
  if (/GROUP BY pv\.option_id\b/.test(sql) && /po\.option_text/.test(sql))
    sql = sql.replace(
      /GROUP BY pv\.option_id\b/g,
      "GROUP BY pv.option_id, po.id",
    );
  if (/GROUP BY LOWER\(TRIM\(pv\.custom_option_text\)\)/.test(sql))
    sql = sql.replace(
      "SELECT TRIM(pv.custom_option_text) t",
      "SELECT MIN(TRIM(pv.custom_option_text)) t",
    );
  if (/GROUP BY TRIM\(pv\.custom_option_text\)/.test(sql))
    sql = sql.replace(
      "SELECT pv.custom_option_text AS option_text",
      "SELECT TRIM(pv.custom_option_text) AS option_text",
    );
  // gathering_answers uses SQLite's implicit insertion order for message replay.
  // Keep an explicit identity column with the same role on PostgreSQL.
  sql = sql.replace(
    /CREATE TABLE IF NOT EXISTS gathering_answers\s*\(/gi,
    "CREATE TABLE IF NOT EXISTS gathering_answers (rowid BIGINT GENERATED ALWAYS AS IDENTITY,",
  );
  sql = sql.replace(/room_type = "personal"/g, "room_type = 'personal'");
  const ignore = /^INSERT OR IGNORE /i.test(sql);
  const replace = /^INSERT OR REPLACE INTO swipe_votes/i.test(sql);
  sql = sql.replace(/^INSERT OR (IGNORE|REPLACE) /i, "INSERT ");
  if (ignore) sql = sql.replace(/;?$/, " ON CONFLICT DO NOTHING");
  if (replace)
    sql = sql.replace(
      /;?$/,
      " ON CONFLICT (poll_id, user_id, option_id) DO UPDATE SET swipe_direction = EXCLUDED.swipe_direction, created_at = EXCLUDED.created_at",
    );
  // Replace placeholders only outside SQL string literals.
  let index = 0;
  sql = sql.replace(/'(?:''|[^'])*'|\?/g, (match) =>
    match === "?" ? `$${++index}` : match,
  );
  if (
    method === "run" &&
    /^INSERT INTO /i.test(sql) &&
    !/\bRETURNING\b/i.test(sql)
  )
    sql = sql.replace(/;?$/, " RETURNING *");
  return { sql };
}
